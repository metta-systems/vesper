#![no_std]
#![no_main]

//! `fp-bench`'s FP component: Doom's view transform and perspective
//! projection, the core of the renderer's `R_AddLine`, done in `f32` over
//! E1M1's vertices (from `doom1.wad`, see `build.rs`). Each frame moves
//! every vertex into the view space of one viewpoint, projects it to a
//! screen column, and sums the visible columns. Vertices are independent:
//! the projection runs four vertices per NEON vector.
//!
//! The frame runs in chunks of [`CHUNK`] vertices. The variants of the same
//! work (`fp-test-protocol`'s `BENCH_*`) are timed with the virtual counter,
//! [`BENCH_RUNS`] times each, in turn: with nothing per chunk, with a
//! `Notification.Signal` nobody waits on (a kernel entry and exit from an FP
//! frame), with a Call into the integer-only `fp-probe`, and with a Call into
//! this component's second instance. Then the report is complete and the
//! worker signals `done`.
//!
//! `nop_entry` is the FP Call target: it Returns at once.

use {
    aarch64_cpu::{
        asm::barrier,
        registers::{CNTVCT_EL0, Read},
    },
    core::sync::atomic::Ordering,
    fp_test_protocol::{
        BENCH_CALL_FP, BENCH_CALL_INTEGER, BENCH_COMPUTE, BENCH_RUNS, BENCH_SIGNAL, BENCH_VARIANTS,
        BenchInit, bench_init, bench_report,
    },
    libobject::{
        NotificationKey, RawKey,
        export::{self, PpcResult},
        invocation::InvocationKey,
        ppc_export,
        thread::ThreadReturnKey,
    },
};

libuser::entry!(main);

/// One viewpoint: where it is, and the cosine and sine of where it looks.
pub struct View {
    x: f32,
    y: f32,
    cos: f32,
    sin: f32,
}

#[expect(
    clippy::approx_constant,
    reason = "generated cosines and sines, some of them 1/√2"
)]
mod vertices {
    //! E1M1's vertices and the viewpoints (generated by `build.rs`).
    use super::View;
    include!(concat!(env!("OUT_DIR"), "/vertices.rs"));
}

use vertices::{VIEWS, XS, YS};

/// Vertices per loop iteration; must match `build.rs`.
const CHUNK: usize = 16;
/// Doom's 320-column screen: its centre and its focal length in columns
/// (`centerxfrac`, 90° field of view).
const CENTER_X: f32 = 160.0;
const FOCAL: f32 = 160.0;
/// The near plane, in map units.
const NEAR: f32 = 4.0;

/// The sum of the screen columns of the visible vertices of one chunk, four
/// vertices per NEON vector: per vertex, `depth = dx·cos + dy·sin` and
/// `side = dx·sin − dy·cos` relative to the viewpoint, the column
/// `160 + side·160 / max(depth, near)` clamped to the screen and truncated,
/// counted only in front of the near plane.
#[inline(always)]
fn project_chunk(xs: &[f32; CHUNK], ys: &[f32; CHUNK], view: &View) -> u32 {
    use core::arch::aarch64::{
        vaddq_f32, vaddq_u32, vaddvq_u32, vandq_u32, vcgtq_f32, vcvtq_s32_f32, vdivq_f32,
        vdupq_n_f32, vdupq_n_u32, vfmaq_f32, vfmsq_f32, vld1q_f32, vmaxnmq_f32, vminnmq_f32,
        vmulq_f32, vreinterpretq_u32_s32, vsubq_f32,
    };
    // SAFETY: the hard-float target has NEON; each load reads four floats
    // inside the chunk.
    unsafe {
        let (view_x, view_y) = (vdupq_n_f32(view.x), vdupq_n_f32(view.y));
        let (cos, sin) = (vdupq_n_f32(view.cos), vdupq_n_f32(view.sin));
        let (near, focal, center) = (vdupq_n_f32(NEAR), vdupq_n_f32(FOCAL), vdupq_n_f32(CENTER_X));
        let (left, right) = (vdupq_n_f32(-1.0), vdupq_n_f32(320.0));
        let mut sum = vdupq_n_u32(0);
        for lane in (0..CHUNK).step_by(4) {
            let dx = vsubq_f32(vld1q_f32(xs.as_ptr().add(lane)), view_x);
            let dy = vsubq_f32(vld1q_f32(ys.as_ptr().add(lane)), view_y);
            let depth = vfmaq_f32(vmulq_f32(dx, cos), dy, sin);
            let side = vfmsq_f32(vmulq_f32(dx, sin), dy, cos);
            let column = vaddq_f32(
                center,
                vdivq_f32(vmulq_f32(side, focal), vmaxnmq_f32(depth, near)),
            );
            let column = vminnmq_f32(vmaxnmq_f32(column, left), right);
            let visible = vcgtq_f32(depth, near);
            let column = vreinterpretq_u32_s32(vcvtq_s32_f32(column));
            sum = vaddq_u32(sum, vandq_u32(column, visible));
        }
        vaddvq_u32(sum)
    }
}

/// The virtual counter, after every earlier instruction.
fn now() -> u64 {
    barrier::isb(barrier::SY);
    CNTVCT_EL0.get()
}

/// What a variant does once per chunk.
struct PerChunk {
    busy: NotificationKey,
    call_integer: InvocationKey,
    call_fp: InvocationKey,
}

impl PerChunk {
    #[inline(always)]
    fn run<const VARIANT: usize>(&self) {
        let result = match VARIANT {
            BENCH_SIGNAL => self.busy.signal(1),
            BENCH_CALL_INTEGER => self.call_integer.call([0; 6]).map(|_| ()),
            BENCH_CALL_FP => self.call_fp.call([0; 6]).map(|_| ()),
            _ => Ok(()),
        };
        result.unwrap_or_else(|error| panic!("fp-bench: variant {VARIANT}: {:?}", error.code()));
    }
}

/// One variant's [`measure`].
type Measure = fn(u64, &PerChunk) -> (u64, u64);

/// Project `frames` frames with `VARIANT`'s work per chunk. Returns the
/// counter ticks taken and the checksum.
#[inline(never)]
fn measure<const VARIANT: usize>(frames: u64, per_chunk: &PerChunk) -> (u64, u64) {
    let (xs, _) = XS.as_chunks::<CHUNK>();
    let (ys, _) = YS.as_chunks::<CHUNK>();
    let mut checksum = 0_u64;
    let started = now();
    for frame in 0..frames {
        let view = &VIEWS[usize::try_from(frame).unwrap_or(0) % VIEWS.len()];
        let mut sum = 0_u32;
        for (xs, ys) in xs.iter().zip(ys) {
            sum = sum.wrapping_add(project_chunk(xs, ys, view));
            per_chunk.run::<VARIANT>();
        }
        checksum = checksum.wrapping_add(u64::from(sum));
    }
    (now() - started, checksum)
}

/// Record the export adapter's `Thread.Return` key (idempotent).
fn setup_return_key(init: &BenchInit) {
    export::init_return_key(&ThreadReturnKey::provisioned(
        u32::try_from(init.guard).unwrap_or(0),
        u8::try_from(init.size_bits).unwrap_or(0),
    ));
}

/// The FP Call target: Returns at once.
extern "C" fn nop_body(
    _dummy0: u64,
    _badge: u64,
    _input0: u64,
    _input1: u64,
    _input2: u64,
    _input3: u64,
    _input4: u64,
    _input5: u64,
) -> PpcResult {
    // SAFETY: the builder fills this instance's init page before any Call.
    setup_return_key(unsafe { bench_init() });
    PpcResult { r0: 0, r1: 0 }
}

ppc_export!(
    /// The FP Call target of the `BENCH_CALL_FP` variant.
    pub fn nop_entry => nop_body
);

fn main(_argument: u64) -> ! {
    // SAFETY: the builder fills and maps both pages before the worker runs.
    let (init, report) = unsafe { (bench_init(), bench_report()) };
    let per_chunk = PerChunk {
        busy: NotificationKey::from_key(RawKey::from_wire(init.busy)),
        call_integer: InvocationKey::from_key(RawKey::from_wire(init.call_integer)),
        call_fp: InvocationKey::from_key(RawKey::from_wire(init.call_fp)),
    };
    let chunks = XS.len() / CHUNK;
    report.vertices.store(
        init.frames * u64::try_from(XS.len()).unwrap_or(0),
        Ordering::Relaxed,
    );
    report.chunks.store(
        init.frames * u64::try_from(chunks).unwrap_or(0),
        Ordering::Relaxed,
    );
    let variants: [Measure; BENCH_VARIANTS] = [
        measure::<BENCH_COMPUTE>,
        measure::<BENCH_SIGNAL>,
        measure::<BENCH_CALL_INTEGER>,
        measure::<BENCH_CALL_FP>,
    ];
    for run in 0..BENCH_RUNS {
        for (variant, measure) in variants.iter().enumerate() {
            let (ticks, checksum) = measure(init.frames, &per_chunk);
            report.ticks[variant][run].store(ticks, Ordering::Relaxed);
            report.checksum[variant].store(checksum, Ordering::Relaxed);
        }
    }
    report.done.store(1, Ordering::Release);
    NotificationKey::from_key(RawKey::from_wire(init.done))
        .signal(1)
        .unwrap_or_else(|error| panic!("fp-bench: done Signal failed: {:?}", error.code()));
    // Take the signals nobody waited for, then park on the next.
    loop {
        let _bits = per_chunk.busy.await_bits(NotificationKey::WAIT_INFINITE);
    }
}
